import { expect, it, vi } from "vitest";
import sharp from "sharp";
import { db } from "@/lib/db";
import { setupDatabase } from "./setup";
import { createCatalogRequestFixture, requestQuoteInput } from "../fixtures/catalog-request-db";
import { changeCatalogRequest } from "@/server/catalog-requests/service";
import { prepareRequestQuote } from "@/server/catalog-requests/prepare-quote";
import { saveCustomer } from "@/server/customers";
import { transitionQuote, getQuote } from "@/server/quotes";
import { convertQuote } from "@/server/sales";
import { createArtPackage, publishRevision, createArtRevision } from "@/server/art/revisions";
import { uploadArtFile } from "@/server/art/files";
import { issueArtAccess, exchangeArtToken } from "@/server/art/access";
import { decideArt } from "@/server/art/decisions";
import { saveOrder, releaseOrder } from "@/server/production/orders";
import { recordProduction } from "@/server/production/reports";
import { saveFinishedStock, openFinishedStock } from "@/server/production/finished-stock";
import { meta, date } from "../fixtures/production";
setupDatabase();
it("keeps the issued document frozen, carries later approval to sale and suspends new production after a replacement", async () => {
  vi.stubEnv("ART_ACCESS_KEY", "a".repeat(64));
  try {
    const { actor, request, lines, product } = await createCatalogRequestFixture();
    const customer = await saveCustomer(actor, undefined, { name: "Ana", type: "PERSON", active: true, document: "", email: "", phone: "", address: "", notes: "" });
    await changeCatalogRequest(actor, request.id, { action: "START", assigneeId: actor.id, expectedVersion: 1 });
    let { quote } = await prepareRequestQuote(actor, request.id, requestQuoteInput(customer.id, lines));
    let revision = await createArtPackage(actor, request.id, { operationKey: "flow-package", sourceLineIds: [lines[0].lineId], instructions: "Conferir nome e cor" });
    const file = { name: "arte.png", bytes: new Uint8Array(await sharp({ create: { width: 4, height: 4, channels: 3, background: "blue" } }).png().toBuffer()) };
    revision = await uploadArtFile(actor, revision.id, revision.version, "flow-upload", file, "FINAL");
    revision = await publishRevision(actor, revision.id, revision.version, "flow-publish");
    quote = await transitionQuote(actor, quote.id, quote.version, "ISSUE");
    const emitted = structuredClone(quote.snapshot);
    expect(emitted?.art?.[0].applicable).toBe(false);
    const link = await issueArtAccess(actor, revision.id, revision.version, "flow-access");
    const session = await exchangeArtToken(new URL(link.url).hash.slice(1));
    await decideArt(session.sessionToken, revision.id, { operationKey: "flow-approve", action: "APPROVE", name: "Ana", comment: "", confirmedManifestHash: revision.manifestHash });
    quote = await getQuote(actor, quote.id);
    expect(quote.snapshot).toEqual(emitted);
    expect(quote.art?.[0].applicable).toBe(true);
    quote = await transitionQuote(actor, quote.id, quote.version, "APPROVE");
    const sale = await convertQuote(actor, quote.id, quote.version, [{ number: 1, amount: quote.totals!.total, dueDate: "2099-12-01" }], "flow-convert");
    expect(sale.art?.[0].applicable).toBe(true);
    expect(sale.snapshot?.art?.[0].applicable).toBe(false);
    const stock = await saveFinishedStock(actor, { ...meta(), productId: product.id });
    await openFinishedStock(actor, { ...meta(stock.version), stockId: stock.id, units: 0, value: "0", effectiveDate: date() });
    let order = await saveOrder(actor, { ...meta(), origin: "SALE", saleId: sale.id, lines: [{ saleLineKey: sale.document.items[0].lineId, productId: product.id, description: "Ana", technology: "FDM", targetUnits: 1 }] });
    order = await releaseOrder(actor, { ...meta(order.version), orderId: order.id });
    const newDraft = await createArtRevision(actor, revision.packageId, { operationKey: "flow-new-draft", instructions: "Revisão" });
    const newFile = await uploadArtFile(actor, newDraft.id, newDraft.version, "flow-next-upload", file, "FINAL");
    await publishRevision(actor, newDraft.id, newFile.version, "flow-next-publish");
    await expect(recordProduction(actor, { ...meta(order.version), lineId: order.lines[0].id, executorId: actor.id, manualStage: true, goodUnits: 1, failedUnits: 0, machineMinutes: null, setupMinutes: "0", finishingMinutes: "0", timeComplete: true, materialComplete: true, materials: [], effectiveDate: date() })).rejects.toMatchObject({ code: "CONFLICT" });
    expect(await db.productionEvent.count({ where: { lineId: order.lines[0].id, kind: "REPORT" } })).toBe(0);
    expect(await db.financialEntry.count()).toBe(1);
    expect(await db.cashMovement.count()).toBe(0);
  } finally { vi.unstubAllEnvs(); }
});
